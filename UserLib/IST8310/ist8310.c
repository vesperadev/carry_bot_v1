/**
 * @file ist8310.c
 * @brief Polling I2C3 IST8310 bring-up + XYZ read (RoboMaster Type-C).
 *
 * Bus:  I2C3 Fast 400 kHz — SCL=PA8, SDA=PC9 (CubeMX)
 * Addr: 7-bit 0x0E → HAL DevAddress 0x1C
 * GPIO: PG6 RSTN (soft-init, active-low pulse), PG3 DRDY (soft-init input)
 *
 * PG6/PG3 are NOT in the current .ioc — driver configures them here so mag
 * works without another CubeMX pass. When labels land in main.h later, these
 * local defines can be removed.
 */
#include "ist8310.h"
#include "ist8310_reg.h"
#include "main.h"
#include "i2c.h"
#include "cmsis_os.h"

/* Soft pin map (Type-C schematic) — not generated by CubeMX yet. */
#ifndef RSTN_IST8310_Pin
#define RSTN_IST8310_Pin GPIO_PIN_6
#define RSTN_IST8310_GPIO_Port GPIOG
#endif
#ifndef DRDY_IST8310_Pin
#define DRDY_IST8310_Pin GPIO_PIN_3
#define DRDY_IST8310_GPIO_Port GPIOG
#endif

#define IST8310_I2C_TIMEOUT_MS 50u
#define IST8310_RST_LOW_MS 50u
#define IST8310_RST_HIGH_MS 50u
#define IST8310_DRDY_WAIT_MS 12u
/** Consecutive sane field reads before mag_ready. */
#define IST8310_MAG_READY_STREAK 5u
/** Earth-field sanity (uT); reject obvious garbage before AHRS mag fuse. */
#define IST8310_FIELD_MIN_UT 20.0f
#define IST8310_FIELD_MAX_UT 120.0f

static void delay_ms(uint32_t ms)
{
  osDelay(ms);
}

static void gpio_soft_init(void)
{
  GPIO_InitTypeDef cfg = {0};

  __HAL_RCC_GPIOG_CLK_ENABLE();

  /* RSTN idle high before mode config */
  HAL_GPIO_WritePin(RSTN_IST8310_GPIO_Port, RSTN_IST8310_Pin, GPIO_PIN_SET);

  cfg.Pin = RSTN_IST8310_Pin;
  cfg.Mode = GPIO_MODE_OUTPUT_PP;
  cfg.Pull = GPIO_PULLUP;
  cfg.Speed = GPIO_SPEED_FREQ_LOW;
  HAL_GPIO_Init(RSTN_IST8310_GPIO_Port, &cfg);

  cfg.Pin = DRDY_IST8310_Pin;
  cfg.Mode = GPIO_MODE_INPUT;
  cfg.Pull = GPIO_NOPULL;
  cfg.Speed = GPIO_SPEED_FREQ_LOW;
  HAL_GPIO_Init(DRDY_IST8310_GPIO_Port, &cfg);
}

static void hw_reset_pulse(void)
{
  HAL_GPIO_WritePin(RSTN_IST8310_GPIO_Port, RSTN_IST8310_Pin, GPIO_PIN_RESET);
  delay_ms(IST8310_RST_LOW_MS);
  HAL_GPIO_WritePin(RSTN_IST8310_GPIO_Port, RSTN_IST8310_Pin, GPIO_PIN_SET);
  delay_ms(IST8310_RST_HIGH_MS);
}

static HAL_StatusTypeDef write_reg(uint8_t reg, uint8_t data)
{
  return HAL_I2C_Mem_Write(&hi2c3, IST8310_I2C_ADDR_HAL, reg,
                           I2C_MEMADD_SIZE_8BIT, &data, 1, IST8310_I2C_TIMEOUT_MS);
}

static HAL_StatusTypeDef read_regs(uint8_t reg, uint8_t *buf, uint16_t len)
{
  return HAL_I2C_Mem_Read(&hi2c3, IST8310_I2C_ADDR_HAL, reg,
                          I2C_MEMADD_SIZE_8BIT, buf, len, IST8310_I2C_TIMEOUT_MS);
}

static uint8_t s_ready_streak;

void IST8310_StructInit(ist8310_t *dev)
{
  if (dev == NULL) {
    return;
  }
  dev->initialized = false;
  dev->mag_ready = false;
  s_ready_streak = 0u;
  dev->raw_mx = 0;
  dev->raw_my = 0;
  dev->raw_mz = 0;
  dev->mag_ut[0] = 0.0f;
  dev->mag_ut[1] = 0.0f;
  dev->mag_ut[2] = 0.0f;
}

uint8_t IST8310_WhoAmI(void)
{
  uint8_t id = 0xFFu;
  if (read_regs(IST8310_REG_WAI, &id, 1) != HAL_OK) {
    return 0xFFu;
  }
  return id;
}

ist8310_err_t IST8310_Init(ist8310_t *dev)
{
  uint8_t id;

  if (dev == NULL) {
    return IST8310_ERR_NO_SENSOR;
  }

  gpio_soft_init();
  hw_reset_pulse();

  if (HAL_I2C_IsDeviceReady(&hi2c3, IST8310_I2C_ADDR_HAL, 5, IST8310_I2C_TIMEOUT_MS) !=
      HAL_OK) {
    dev->initialized = false;
    return IST8310_ERR_NO_SENSOR;
  }

  id = IST8310_WhoAmI();
  if (id != IST8310_WAI_VALUE) {
    dev->initialized = false;
    return IST8310_ERR_WHOAMI;
  }

  if (write_reg(IST8310_REG_AVGCNTL, IST8310_AVGCNTL_VALUE) != HAL_OK ||
      write_reg(IST8310_REG_PDCNTL, IST8310_PDCNTL_VALUE) != HAL_OK ||
      write_reg(IST8310_REG_CNTL1, IST8310_CNTL1_CONT_200HZ) != HAL_OK) {
    dev->initialized = false;
    return IST8310_ERR_COMM;
  }

  delay_ms(10);
  dev->initialized = true;
  dev->mag_ready = false;
  s_ready_streak = 0u;
  return IST8310_OK;
}

bool IST8310_DataReadyPin(void)
{
  return (HAL_GPIO_ReadPin(DRDY_IST8310_GPIO_Port, DRDY_IST8310_Pin) == GPIO_PIN_SET);
}

bool IST8310_WaitDataReady(uint32_t timeout_ms)
{
  uint32_t start = osKernelGetTickCount();
  while ((osKernelGetTickCount() - start) < timeout_ms) {
    if (IST8310_DataReadyPin()) {
      return true;
    }
    osDelay(1);
  }
  return IST8310_DataReadyPin();
}

static bool mag_field_sane_ut(const float mag_ut[3])
{
  const float b2 =
      mag_ut[0] * mag_ut[0] + mag_ut[1] * mag_ut[1] + mag_ut[2] * mag_ut[2];

  if (b2 <= 0.0f) {
    return false;
  }
  if (b2 < (IST8310_FIELD_MIN_UT * IST8310_FIELD_MIN_UT)) {
    return false;
  }
  if (b2 > (IST8310_FIELD_MAX_UT * IST8310_FIELD_MAX_UT)) {
    return false;
  }
  return true;
}

static void mag_note_readiness(ist8310_t *dev)
{
  if (dev == NULL) {
    return;
  }
  if (mag_field_sane_ut(dev->mag_ut)) {
    if (s_ready_streak < 255u) {
      s_ready_streak++;
    }
  } else {
    s_ready_streak = 0u;
  }
  dev->mag_ready = (s_ready_streak >= IST8310_MAG_READY_STREAK);
}

ist8310_err_t IST8310_ReadRaw(ist8310_t *dev)
{
  uint8_t buf[6];

  if (dev == NULL || !dev->initialized) {
    return IST8310_ERR_NO_SENSOR;
  }

  if (read_regs(IST8310_REG_DATAXL, buf, 6) != HAL_OK) {
    return IST8310_ERR_COMM;
  }

  /* Little-endian int16 per axis (XL,XH ...) */
  dev->raw_mx = (int16_t)((uint16_t)buf[1] << 8 | buf[0]);
  dev->raw_my = (int16_t)((uint16_t)buf[3] << 8 | buf[2]);
  dev->raw_mz = (int16_t)((uint16_t)buf[5] << 8 | buf[4]);
  return IST8310_OK;
}

ist8310_err_t IST8310_Read(ist8310_t *dev)
{
  ist8310_err_t err;

  if (dev == NULL || !dev->initialized) {
    return IST8310_ERR_NO_SENSOR;
  }

  (void)IST8310_WaitDataReady(IST8310_DRDY_WAIT_MS);

  err = IST8310_ReadRaw(dev);
  if (err != IST8310_OK) {
    s_ready_streak = 0u;
    dev->mag_ready = false;
    return err;
  }

  dev->mag_ut[0] = (float)dev->raw_mx * IST8310_MAG_SEN;
  dev->mag_ut[1] = (float)dev->raw_my * IST8310_MAG_SEN;
  dev->mag_ut[2] = (float)dev->raw_mz * IST8310_MAG_SEN;
  mag_note_readiness(dev);

  return IST8310_OK;
}

